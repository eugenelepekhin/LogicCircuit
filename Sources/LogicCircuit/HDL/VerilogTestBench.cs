// Ignore Spelling: Verilog

using System;
using System.Collections.Generic;
using System.Globalization;

namespace LogicCircuit {
	internal sealed class VerilogTestBench : T4Transformation {
		private readonly VerilogHdl verilogHdl;
		private readonly string circuitName;
		private readonly List<InputPinSocket> inputs;
		private readonly List<OutputPinSocket> outputs;
		private readonly IList<TruthState> table;
		private readonly Func<string, string> fixName;

		public VerilogTestBench(VerilogHdl verilogHdl, string circuitName, List<InputPinSocket> inputs, List<OutputPinSocket> outputs, IList<TruthState> table, Func<string, string> fixName) {
			this.verilogHdl = verilogHdl;
			this.circuitName = fixName(circuitName);
			this.inputs = inputs;
			this.outputs = outputs;
			this.table = table;
			this.fixName = fixName;
			this.ToStringHelper.FormatProvider = CultureInfo.InvariantCulture;
		}

		public string Range(BasePin pin) => this.verilogHdl.Range(pin);

		public override string TransformText() {
			this.WriteLine("// This file is generated by LogicCircuit version {0} from circuit {1}", DialogAbout.CurrentVersion(),  this.circuitName);
			this.WriteLine("module {0}_TestBench;", this.circuitName);

			this.WriteLine("\tstruct packed {");
			foreach(InputPinSocket input in this.inputs) {
				if(input.Pin.BitWidth == 1) {
					this.WriteLine("\t\tbit {0};", this.fixName(input.Pin.Name));
				} else {
					this.WriteLine("\t\tbit{0} {1};", this.Range(input.Pin), this.fixName(input.Pin.Name));
				}
			}
			foreach(OutputPinSocket output in this.outputs) {
				if(output.Pin.BitWidth == 1) {
					this.WriteLine("\t\tlogic {0};", this.fixName(output.Pin.Name));
				} else {
					this.WriteLine("\t\tlogic{0} {1};", this.Range(output.Pin), this.fixName(output.Pin.Name));
				}
			}

			this.WriteLine("\t}} TestBenchTruthState[{0}] = '{{", this.table.Count);
			
			int stateIndex = 0;
			foreach(TruthState state in this.table) {
				int inputIndex = 0;
				if(0 < stateIndex) {
					this.WriteLine(",");
				}
				this.Write("\t\t'{");
				bool pinComa = false;
				foreach(InputPinSocket input in this.inputs) {
					if(pinComa) {
						this.Write(", ");
					} else {
						pinComa = true;
					}
					this.Write("{0}", state.Input[inputIndex]);
					inputIndex++;
				}
				int outputIndex = 0;
				foreach(OutputPinSocket output in this.outputs) {
					if(pinComa) {
						this.Write(", ");
					} else {
						pinComa = true;
					}
					string value = state[outputIndex];
					if(value.Contains('-', StringComparison.Ordinal)) {
						value = value.Replace('-', 'z');
						this.Write("{0}'b{1}", output.Pin.BitWidth, value);
					} else {
						this.Write("'h{0}", value);
					}
					outputIndex++;
				}
				this.Write("}");
				stateIndex++;
			}
			this.WriteLine();
			this.WriteLine("\t};");
			this.WriteLine();

			foreach(InputPinSocket input in this.inputs) {
				this.WriteLine("\treg {0}{1};", this.Range(input.Pin), this.fixName(input.Pin.Name));
			}
			foreach(OutputPinSocket output in this.outputs) {
				this.WriteLine("\twire {0}{1};", this.Range(output.Pin), this.fixName(output.Pin.Name));
			}
			this.WriteLine();

			this.WriteLine("\t{0} u0(", this.circuitName);
			bool comma = false;
			foreach(InputPinSocket input in this.inputs) {
				if(comma) this.WriteLine(",");
				this.Write("\t\t.{0}({0})", this.fixName(input.Pin.Name));
				comma = true;
			}
			foreach(OutputPinSocket output in this.outputs) {
				if(comma) this.WriteLine(",");
				this.Write("\t\t.{0}({0})", this.fixName(output.Pin.Name));
				comma = true;
			}
			this.WriteLine();
			this.WriteLine("\t);");

			this.WriteLine();
			this.WriteLine("\tinitial begin");

			this.WriteLine("\t\t$display(\"Starting test bench for {0}_TestBench\");", this.circuitName);
			this.WriteLine("\t\tforeach(TestBenchTruthState[i]) begin");

			foreach(InputPinSocket input in this.inputs) {
				this.WriteLine("\t\t\t{0} = TestBenchTruthState[i].{0};", this.fixName(input.Pin.Name));
			}
			this.WriteLine("\t\t\t#10;");

			foreach(OutputPinSocket output in this.outputs) {
				this.WriteLine("\t\t\tif({0} !== TestBenchTruthState[i].{0}) begin", this.fixName(output.Pin.Name));
				this.WriteLine("\t\t\t\t$error(\"Output {0} expected value 0b%0b actual value is 0b%0b for i=%0d\", TestBenchTruthState[i].{0}, {0}, i);", this.fixName(output.Pin.Name));
				this.WriteLine("\t\t\tend");
			}

			this.WriteLine("\t\tend");
			this.WriteLine("\t\t$display(\"Test bench completed for {0}_TestBench\");", this.circuitName);
			this.WriteLine("\t\t$finish;");
			this.WriteLine("\tend");
			this.WriteLine("endmodule // {0}_TestBench", this.circuitName);

			return this.GenerationEnvironment.ToString();
		}
	}
}
